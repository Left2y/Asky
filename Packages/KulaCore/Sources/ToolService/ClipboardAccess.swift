import AppKit
import LocalStore
import UniformTypeIdentifiers

/// Native clipboard boundary. History never requires an agent or paste permission.
@MainActor
public enum ClipboardAccess {
    public struct Snapshot {
        public let changeCount: Int
        public let text: String?
        public let image: Data?
        public let sourceName: String?
        public let sourceBundleID: String?
        public let concealed: Bool
    }

    public static var changeCount: Int { NSPasteboard.general.changeCount }

    public static func snapshot() -> Snapshot {
        let pb = NSPasteboard.general
        let excluded = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        let concealed = !(pb.types ?? []).filter { excluded.contains($0.rawValue) }.isEmpty
        let app = NSWorkspace.shared.frontmostApplication
        return Snapshot(changeCount: pb.changeCount, text: concealed ? nil : pb.string(forType: .string),
                        image: concealed ? nil : (pb.data(forType: .png) ?? pb.data(forType: .tiff)),
                        sourceName: app?.localizedName, sourceBundleID: app?.bundleIdentifier, concealed: concealed)
    }

    public static func sourceIcon(named name: String?) -> NSImage? {
        guard let name else { return nil }
        if let icon = NSWorkspace.shared.runningApplications.first(where: { $0.localizedName == name })?.icon { return icon }
        if let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: name) {
            return NSWorkspace.shared.icon(forFile: url.path)
        }
        for directory in ["/Applications", "/System/Applications", "/System/Applications/Utilities"] {
            let path = URL(filePath: directory).appendingPathComponent(name + ".app").path
            if FileManager.default.fileExists(atPath: path) { return NSWorkspace.shared.icon(forFile: path) }
        }
        return nil
    }

    /// Validate before clearing, so a deleted image cannot erase the user's clipboard.
    @discardableResult
    public static func copy(_ item: ClipboardItem, to pasteboard: NSPasteboard = .general) -> Bool {
        if item.kind == .text, let text = item.text {
            pasteboard.clearContents()
            return pasteboard.setString(text, forType: .string)
        }
        guard let path = item.filePath, let image = NSImage(contentsOfFile: path), let data = image.tiffRepresentation else { return false }
        pasteboard.clearContents()
        return pasteboard.setData(data, forType: .tiff)
    }

    public static func dragProvider(for item: ClipboardItem) -> NSItemProvider? {
        if item.kind == .text, let text = item.text { return NSItemProvider(object: text as NSString) }
        guard let path = item.filePath, let image = NSImage(contentsOfFile: path) else { return nil }
        return NSItemProvider(object: image)
    }
}
