import AppKit
import LocalStore
import UniformTypeIdentifiers
import ImageIO

/// Native clipboard boundary. History never requires an agent or paste permission.
@MainActor
public enum ClipboardAccess {
    public struct Snapshot {
        public let changeCount: Int
        public let text: String?
        public let image: Data?
        public let fileURLs: [URL]
        public let sourceName: String?
        public let sourceBundleID: String?
        public let concealed: Bool
        public let restoredFromHistory: Bool
    }

    public static var changeCount: Int { NSPasteboard.general.changeCount }

    public static func snapshot(from pb: NSPasteboard = .general) -> Snapshot {
        let excluded = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        let concealed = !(pb.types ?? []).filter { excluded.contains($0.rawValue) }.isEmpty
        let app = NSWorkspace.shared.frontmostApplication
        let urls = concealed ? [] : fileURLs(from: pb)
        // Chat apps can publish a temporary image file plus its filename instead of bitmap data.
        // Keep multi-file selections intact; snapshot a single image before the source removes it.
        let image = concealed || urls.count > 1 ? nil :
            (imageData(from: pb) ?? imageFileData(from: urls))
        return Snapshot(changeCount: pb.changeCount, text: concealed ? nil : pb.string(forType: .string),
                        image: image,
                        fileURLs: image == nil ? urls : [],
                        sourceName: app?.localizedName, sourceBundleID: app?.bundleIdentifier, concealed: concealed,
                        restoredFromHistory: pb.string(forType: historyRestoreType) != nil)
    }

    private static func imageData(from pasteboard: NSPasteboard) -> Data? {
        // Some chat clients publish JPEG/HEIC instead of the usual PNG/TIFF flavors.
        let types = [.png, .tiff] + (pasteboard.types ?? []).filter {
            $0 != .png && $0 != .tiff && UTType($0.rawValue)?.conforms(to: .image) == true
        }
        for type in types {
            guard let data = pasteboard.data(forType: type), isImageData(data) else { continue }
            return data
        }
        return nil
    }

    private static func isImageData(_ data: Data) -> Bool {
        guard !data.isEmpty, data.count <= 20 * 1024 * 1024,
              let source = CGImageSourceCreateWithData(data as CFData, nil),
              CGImageSourceGetCount(source) > 0,
              CGImageSourceCopyPropertiesAtIndex(source, 0, nil) != nil else { return false }
        return true
    }

    private static func imageFileData(from urls: [URL]) -> Data? {
        guard urls.count == 1, let url = urls.first,
              let values = try? url.resourceValues(forKeys: [.isRegularFileKey, .fileSizeKey, .contentTypeKey]),
              values.isRegularFile == true, values.contentType?.conforms(to: .image) == true,
              let size = values.fileSize, size > 0, size <= 20 * 1024 * 1024,
              let data = try? Data(contentsOf: url, options: .mappedIfSafe),
              isImageData(data) else { return nil }
        return data
    }

    private static func fileURLs(from pasteboard: NSPasteboard) -> [URL] {
        let hasFileURLs = pasteboard.pasteboardItems?.contains { $0.types.contains(.fileURL) } == true
        let urls = hasFileURLs ? ((pasteboard.readObjects(forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []) : []
        if !urls.isEmpty { return urls.filter(\.isFileURL) }
        // Older file managers publish a filename list instead of public.file-url.
        let paths = pasteboard.propertyList(forType: NSPasteboard.PasteboardType("NSFilenamesPboardType")) as? [String] ?? []
        return paths.filter { $0.hasPrefix("/") }.map { URL(filePath: $0) }
    }

    private static func availableFiles(for item: ClipboardItem) -> [URL]? {
        let urls = item.filePaths.map { URL(filePath: $0) }
        guard !urls.isEmpty, urls.allSatisfy({ FileManager.default.isReadableFile(atPath: $0.path) }) else { return nil }
        return urls
    }

    /// Resolve one readable movie for native preview without loading the video into history.
    public static func videoPreviewURL(for item: ClipboardItem) -> URL? {
        guard item.kind == .file, item.filePaths.count == 1,
              let url = availableFiles(for: item)?.first,
              let values = try? url.resourceValues(forKeys: [.isRegularFileKey, .contentTypeKey]),
              values.isRegularFile == true,
              values.contentType?.conforms(to: .movie) == true else { return nil }
        return url
    }

    public static func fileIcon(for item: ClipboardItem) -> NSImage? {
        guard item.kind == .file, let path = item.filePaths.first else { return nil }
        return NSWorkspace.shared.icon(forFile: path)
    }

    private static var iconCache: [String: NSImage?] = [:]

    /// Prefers the bundle ID; legacy rows only stored the (possibly localized) app name.
    public static func sourceIcon(bundleID: String?, name: String?) -> NSImage? {
        let key = (bundleID ?? "") + "|" + (name ?? "")
        if let cached = iconCache[key] { return cached }
        let icon = resolveIcon(bundleID: bundleID, name: name)
        iconCache[key] = icon
        return icon
    }

    private static func resolveIcon(bundleID: String?, name: String?) -> NSImage? {
        let workspace = NSWorkspace.shared
        if let bundleID, let url = workspace.urlForApplication(withBundleIdentifier: bundleID) {
            return workspace.icon(forFile: url.path)
        }
        guard let name, !name.isEmpty else { return nil }
        if let icon = workspace.runningApplications.first(where: { $0.localizedName == name })?.icon { return icon }
        if let url = workspace.urlForApplication(withBundleIdentifier: name) { return workspace.icon(forFile: url.path) }
        let fm = FileManager.default
        for directory in ["/Applications", "/System/Applications", "/System/Applications/Utilities",
                          "/Applications/Utilities", fm.homeDirectoryForCurrentUser.appending(path: "Applications").path] {
            let direct = URL(filePath: directory).appendingPathComponent(name + ".app").path
            if fm.fileExists(atPath: direct) { return workspace.icon(forFile: direct) }
            // Localized names (备忘录 → Notes.app) only match the display name.
            for entry in (try? fm.contentsOfDirectory(atPath: directory)) ?? [] where entry.hasSuffix(".app") {
                let path = URL(filePath: directory).appendingPathComponent(entry).path
                let display = (fm.displayName(atPath: path) as NSString).deletingPathExtension
                if display == name { return workspace.icon(forFile: path) }
            }
        }
        return nil
    }

    private static let historyRestoreType = NSPasteboard.PasteboardType("app.asky.clipboard-history-restore")

    private static func markRestored(_ item: ClipboardItem, on pasteboard: NSPasteboard, success: Bool) -> Bool {
        if success { pasteboard.setString(item.id, forType: historyRestoreType) }
        return success
    }

    /// Validate before clearing, so unavailable originals cannot erase the user's clipboard.
    @discardableResult
    public static func copy(_ item: ClipboardItem, to pasteboard: NSPasteboard = .general) -> Bool {
        if item.kind == .file {
            guard let urls = availableFiles(for: item) else { return false }
            pasteboard.clearContents()
            return markRestored(item, on: pasteboard, success: pasteboard.writeObjects(urls.map { $0 as NSURL }))
        }
        if item.kind == .text, let text = item.text {
            pasteboard.clearContents()
            return markRestored(item, on: pasteboard, success: pasteboard.setString(text, forType: .string))
        }
        guard let path = item.filePath, let image = NSImage(contentsOfFile: path), let data = image.tiffRepresentation else { return false }
        pasteboard.clearContents()
        return markRestored(item, on: pasteboard, success: pasteboard.setData(data, forType: .tiff))
    }

    /// Sends ⌘V to the frontmost app. Requires Accessibility; prompts once when missing.
    public static func pasteIntoFrontmostApp() -> Bool {
        guard AXIsProcessTrustedWithOptions(["AXTrustedCheckOptionPrompt": true] as CFDictionary) else { return false }
        let source = CGEventSource(stateID: .hidSystemState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: down)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
        return true
    }

    /// Eager pasteboard data for an AppKit drag. Chromium/Electron targets (Feishu, browsers) ignore lazy
    /// NSItemProvider promises and only accept plain text or a real file URL, so both are written up front.
    public static func dragItem(for item: ClipboardItem,
                                exportDirectory: URL = FileManager.default.temporaryDirectory.appending(path: "AskyDrag")) -> NSPasteboardItem? {
        // Files require NSURL writers; use dragItems to retain access grants and all selected files.
        guard item.kind != .file else { return nil }
        let pbItem = NSPasteboardItem()
        if item.kind == .text, let text = item.text {
            return pbItem.setString(text, forType: .string) ? pbItem : nil
        }
        guard let png = item.filePath.flatMap(pngData(atPath:)) else { return nil }
        // Stored originals use a typeless ".img" name; targets need a real extension to recognise the image.
        let file = exportDirectory.appending(path: "\(item.id).png")
        do {
            try FileManager.default.createDirectory(at: exportDirectory, withIntermediateDirectories: true)
            if !FileManager.default.fileExists(atPath: file.path) { try png.write(to: file) }
        } catch { return nil }
        pbItem.setString(file.absoluteString, forType: .fileURL)
        pbItem.setData(png, forType: .png)
        return pbItem
    }

    /// One dragging item per file keeps multi-file selections intact at native destinations.
    public static func dragItems(for item: ClipboardItem) -> [any NSPasteboardWriting]? {
        guard item.kind == .file else { return dragItem(for: item).map { [$0] } }
        guard let urls = availableFiles(for: item) else { return nil }
        // AppKit recognizes NSURL writers and attaches sandbox extensions for receiving apps.
        // A hand-written public.file-url works in Finder but cannot grant a sandboxed target access.
        return urls.map { $0 as NSURL }
    }

    private static func pngData(atPath path: String) -> Data? {
        guard let data = FileManager.default.contents(atPath: path) else { return nil }
        if data.starts(with: [0x89, 0x50, 0x4E, 0x47]) { return data }
        return NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
    }
}
